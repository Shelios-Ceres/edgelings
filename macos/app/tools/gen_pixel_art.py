#!/usr/bin/env python3
"""Generates macos/app/Sources/PixelArt.swift from the Windows pixel kit's
icon, face and logo grids (PixelIconData.cs, PixelIconData.Looks.cs), so the
Mac app draws the same 10 x 10 art. Run from the repo root."""
import re

SRC = "windows/src/AgentIsland.WinUI/Shell/"
data = open(SRC + "PixelIconData.cs", encoding="utf-8").read()
looks = open(SRC + "PixelIconData.Looks.cs", encoding="utf-8").read()

def rows_of(block):
    return re.findall(r'"([^"]*)"', block)

def colors_of(block):
    return [(m.group(1), int(m.group(2), 16)) for m in re.finditer(r"\('(.)',\s*0x([0-9A-Fa-f]+)u\)", block)]

icons = {}
for m in re.finditer(r'\["(\w+)"\]\s*=\s*\("([0-9A-F]{4})",\s*new\[\]\s*\{(.*?)\}\)', data, re.S):
    icons[m.group(1)] = (m.group(2), rows_of(m.group(3)))

face_entry = re.compile(r'\[(?:DisplayProvider\.(\w+)|\(DisplayProvider\.(\w+),\s*"([\w-]+)"\))\]\s*=\s*\(new\[\]\s*\{(.*?)\},\s*new\[\]\s*\{(.*?)\}\),', re.S)
faces, lookfaces = {}, {}
for m in face_entry.finditer(data):
    if m.group(1):
        faces[m.group(1).lower()] = (rows_of(m.group(4)), colors_of(m.group(5)))
for m in face_entry.finditer(looks):
    if m.group(2):
        lookfaces[m.group(2).lower() + "/" + m.group(3)] = (rows_of(m.group(4)), colors_of(m.group(5)))

logo = re.search(r"LogoGrid = \(new\[\]\s*\{(.*?)\},\s*new\[\]\s*\{(.*?)\}\);", data, re.S)

def swift_rows(rows):
    return "[" + ", ".join('"%s"' % r for r in rows) + "]"

def swift_colors(colors):
    return "[" + ", ".join('"%s": 0x%06X' % (k, v) for k, v in colors) + "]"

out = ["// Generated by macos/app/tools/gen_pixel_art.py from the Windows pixel kit's grids",
       "// (PixelIconData.cs, PixelIconData.Looks.cs). Do not edit by hand.",
       "",
       "struct PixelGrid {",
       "    let rows: [String]",
       "    let colors: [Character: UInt32]",
       "}",
       "",
       "enum PixelArt {",
       "    /// One-colour icons by name; `replaces` is the Segoe glyph each stands in for.",
       "    static let icons: [String: [String]] = ["]
for name, (glyph, rows) in sorted(icons.items()):
    out.append('        "%s": %s,' % (name, swift_rows(rows)))
out.append("    ]")
out.append("")
out.append("    static let glyphs: [String: String] = [")
for name, (glyph, rows) in sorted(icons.items()):
    out.append('        "%s": "%s",' % (glyph, name))
out.append("    ]")
out.append("")
out.append("    /// Each agent's default face, by agent id.")
out.append("    static let faces: [String: PixelGrid] = [")
for name, (rows, colors) in sorted(faces.items()):
    out.append('        "%s": PixelGrid(rows: %s, colors: %s),' % (name, swift_rows(rows), swift_colors(colors).replace('"', 'Character("', 0)))
out.append("    ]")
out.append("")
out.append('    /// Faces of the looks other than the default, keyed "agent/look".')
out.append("    static let lookFaces: [String: PixelGrid] = [")
for name, (rows, colors) in sorted(lookfaces.items()):
    out.append('        "%s": PixelGrid(rows: %s, colors: %s),' % (name, swift_rows(rows), swift_colors(colors)))
out.append("    ]")
out.append("")
out.append("    static let logo = PixelGrid(rows: %s, colors: %s)" % (swift_rows(rows_of(logo.group(1))), swift_colors(colors_of(logo.group(2)))))
out.append("}")
open("macos/app/Sources/PixelArt.swift", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(icons), "icons,", len(faces), "faces,", len(lookfaces), "look faces")
