#!/usr/bin/env python3
"""Generates Core's Model/StateGroups.Data.cs from the two design tables.

    python windows/tools/gen_state_groups.py [<state-groups.pixel.json> <classic-groups.json> [<out.cs>]]

With no arguments it reads the two tables beside it (windows/tools/state-groups/), which are the
source: a design chat that changes a table edits that copy.

The Pixel table comes from the Pixel design chat, the Classic one from the
Classic chat (both approved 2026-11-02). Only the per-look pairs and the
own-state sets are carried over; the phase groups and the timings are
asserted against what StateGroups.cs hard-codes, so a changed table fails
here instead of drifting silently.
"""
import json
import sys
from pathlib import Path

THINK = ["thinking", "streaming", "compacting"]
DO = ["reading", "searching", "web", "writing", "running", "controlling", "working"]
TEAM = ["spawning", "orbit", "sending"]
TIMINGS = dict(first=12, main=8, second=5, minSegment=4, minDwell=2)


def pair(slots):
    return "null" if slots is None else f'new("{slots[0]}", "{slots[1]}")'


def pixel_pair(entry):
    if entry is None:
        return None
    assert entry["second"] == "tool", entry
    return (entry["main"], entry["secondIfNoTool"])


def classic_pair(slots):
    return None if slots is None else (slots[0], slots[1])


def looks_block(name, rows):
    lines = [f"    private static readonly Dictionary<string, LookGroups> {name} = new()", "    {"]
    for key, groups in rows:
        parts = ", ".join(f"{g.capitalize()}: {pair(groups.get(g))}" for g in ("think", "do", "team", "busy"))
        lines.append(f'        ["{key}"] = new({parts}),')
    lines += ["    };", ""]
    return lines


def tools_block(name, tools):
    lines = [f"    private static readonly Dictionary<WorkGroup, string[]> {name} = new()", "    {"]
    for group in ("think", "do", "team", "busy"):
        states = tools.get(group, [])
        body = "new[] { " + ", ".join(f'"{s}"' for s in states) + " }" if states else "Array.Empty<string>()"
        lines.append(f"        [WorkGroup.{group.capitalize()}] = {body},")
    lines += ["    };", ""]
    return lines


def main():
    here = Path(__file__).resolve().parent
    pixel_path = Path(sys.argv[1]) if len(sys.argv) > 1 else here / "state-groups" / "state-groups.pixel.json"
    classic_path = Path(sys.argv[2]) if len(sys.argv) > 2 else here / "state-groups" / "classic-groups.json"
    out_path = Path(sys.argv[3]) if len(sys.argv) > 3 else here.parent / "src" / "AgentIsland.Core" / "Model" / "StateGroups.Data.cs"
    pixel = json.loads(pixel_path.read_text(encoding="utf-8"))
    classic = json.loads(classic_path.read_text(encoding="utf-8"))

    assert pixel["groups"]["think"] == THINK and pixel["groups"]["do"] == DO and pixel["groups"]["team"] == TEAM, "Pixel groups"
    assert pixel["groups"]["busy"] == THINK + DO, "Pixel busy"
    t = pixel["timings"]
    assert (t["firstMainSeconds"], t["mainSeconds"], t["secondSeconds"], t["minSegmentSeconds"], t["minDwellBetweenGroupsSeconds"]) == tuple(TIMINGS.values()), "Pixel timings"
    t = classic["timings"]
    assert (t["rotateAfterSeconds"], t["mainSegmentSeconds"], t["secondSegmentSeconds"], t["minSegmentSeconds"], t["minDwellBetweenGroupsSeconds"]) == tuple(TIMINGS.values()), "Classic timings"
    state = classic["phaseToState"]
    assert [state[p] for p in ("Thinking", "Streaming", "Compacting")] == THINK
    assert [state[p] for p in ("Reading", "Searching", "WebSearching", "Writing", "Running", "Controlling", "Working")] == DO
    assert [state[p] for p in ("Spawning", "WaitingOnAgents", "Sending")] == TEAM

    pixel_rows = []
    for key, entry in pixel["looks"].items():
        pixel_rows.append((key, {g: pixel_pair(entry.get(g)) for g in ("think", "do", "team", "busy")}))
    classic_rows = []
    for key, entry in classic["looks"].items():
        classic_rows.append((key, {g: classic_pair(entry.get(g)) for g in ("think", "do", "team", "busy")}))

    classic_tools = {g: [state[p] for p in phases] for g, phases in classic["ownStatePhases"].items()}

    out = [
        "// Generated by windows/tools/gen_state_groups.py from windows/tools/state-groups/state-groups.pixel.json",
        "// and classic-groups.json (the Pixel and Classic design chats' tables, approved 2026-11-02). Do not edit by hand;",
        "// StateGroupsTests checks every look against the engines the app ships.",
        "namespace AgentIsland.Model;",
        "",
        "public static partial class StateGroups",
        "{",
    ]
    out += looks_block("PixelLooks", pixel_rows)
    out += looks_block("ClassicLooks", classic_rows)
    out += tools_block("PixelTools", pixel["toolStates"])
    out += tools_block("ClassicTools", classic_tools)
    out[-1:] = []
    out.append("}")
    out_path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


main()
